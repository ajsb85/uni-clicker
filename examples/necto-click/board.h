#ifndef UNI_CLICKER_NECTO_BOARD_H
#define UNI_CLICKER_NECTO_BOARD_H

#include "hal_ll_pin_names.h"
#include "delays.h"

/* MikroBUS 1 on UNI Clicker with the STM32F746ZG SiBRAIN card. */
#define MIKROBUS_1_MIKROBUS_AN  GPIO_PA3
#define MIKROBUS_1_MIKROBUS_RST GPIO_PE11
#define MIKROBUS_1_MIKROBUS_CS  GPIO_PA4
#define MIKROBUS_1_MIKROBUS_SCK GPIO_PA5
#define MIKROBUS_1_MIKROBUS_MISO GPIO_PA6
#define MIKROBUS_1_MIKROBUS_MOSI GPIO_PB5
#define MIKROBUS_1_MIKROBUS_PWM GPIO_PD12
#define MIKROBUS_1_MIKROBUS_RX  GPIO_PB7
#define MIKROBUS_1_MIKROBUS_TX  GPIO_PB6
#define MIKROBUS_1_MIKROBUS_SCL GPIO_PB8
#define MIKROBUS_1_MIKROBUS_SDA GPIO_PB9
#define MIKROBUS_1_MIKROBUS_INT GPIO_PD3

/* Socket 2 shares SPI1 and I2C1 with socket 1 and uses USART2. */
#define MIKROBUS_2_MIKROBUS_AN  GPIO_PC0
#define MIKROBUS_2_MIKROBUS_RST GPIO_PE12
#define MIKROBUS_2_MIKROBUS_CS  GPIO_PB2
#define MIKROBUS_2_MIKROBUS_SCK GPIO_PA5
#define MIKROBUS_2_MIKROBUS_MISO GPIO_PA6
#define MIKROBUS_2_MIKROBUS_MOSI GPIO_PB5
#define MIKROBUS_2_MIKROBUS_PWM GPIO_PD13
#define MIKROBUS_2_MIKROBUS_RX  GPIO_PD6
#define MIKROBUS_2_MIKROBUS_TX  GPIO_PD5
#define MIKROBUS_2_MIKROBUS_SCL GPIO_PB8
#define MIKROBUS_2_MIKROBUS_SDA GPIO_PB9
#define MIKROBUS_2_MIKROBUS_INT GPIO_PD4
#define MIKROBUS(socket, pin) socket##_##pin

#endif
